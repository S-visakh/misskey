import { describe, it } from 'node:test';
import assert from 'node:assert/strict';

describe('CH02 - First-Class Audio Posts with Transcription', () => {
function isAudioMime(mime: string): boolean {
return mime.startsWith('audio/') || mime === 'application/ogg';
}

function sanitizeTranscript(text: string): string {
return text.trim();
}

it('validates supported audio MIME types', () => {
assert.equal(isAudioMime('audio/mp3'), true);
assert.equal(isAudioMime('audio/wav'), true);
assert.equal(isAudioMime('audio/ogg'), true);
assert.equal(isAudioMime('image/png'), false);
assert.equal(isAudioMime('video/mp4'), false);
});

it('sanitizes and preserves transcripts', () => {
const raw = '  Welcome to this podcast episode.  ';
assert.equal(sanitizeTranscript(raw), 'Welcome to this podcast episode.');
});

it('formats transcript metadata record', () => {
const transcript = {
fileId: 'file_audio_100',
text: 'Spoken transcript content',
language: 'en',
isAutoGenerated: false,
};

assert.equal(transcript.fileId, 'file_audio_100');
assert.equal(transcript.isAutoGenerated, false);
});
});
