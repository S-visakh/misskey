import { PrimaryColumn, Entity, Column, ManyToOne, JoinColumn } from 'typeorm';
import { id } from './util/id.js';
import { MiDriveFile } from './DriveFile.js';

@Entity('drive_file_audio_transcript')
export class MiAudioTranscript {
@PrimaryColumn(id())
public fileId: MiDriveFile['id'];

@ManyToOne(() => MiDriveFile, {
onDelete: 'CASCADE',
})
@JoinColumn()
public file: MiDriveFile | null;

@Column('text')
public text: string;

@Column('varchar', {
length: 16,
default: 'en',
})
public language: string;

@Column('boolean', {
default: false,
})
public isAutoGenerated: boolean;

@Column('timestamp with time zone', {
default: () => 'CURRENT_TIMESTAMP',
})
public updatedAt: Date;
}
